// ================= 数据访问接口 =================
const LegoGalaxy = {
    // 获取统计数据
    getStats() {
        return STATS_SUMMARY;
    },
    
    // 获取时间线数据
    getTimeline(yearRange = null) {
        if (!yearRange) return TIMELINE_DATA;
        return TIMELINE_DATA.filter(d => 
            d.year >= yearRange[0] && d.year <= yearRange[1]
        );
    },
    
    // 获取主题数据
    getThemeById(id) {
        return THEME_POPULARITY.find(t => t.id === id);
    },
    
    // 按维度排序主题
    sortThemesBy(metric = 'composite', limit = 20) {
        const metricMap = {
            'sets': 'by_sets',
            'parts': 'by_parts',
            'longevity': 'by_longevity',
            'composite': 'composite'
        };
        
        const sortKey = metricMap[metric] || 'composite';
        return [...THEME_POPULARITY]
            .sort((a, b) => a.rankings[sortKey] - b.rankings[sortKey])
            .slice(0, limit);
    },
    
    // 获取复杂度数据
    getComplexityTrend() {
        return COMPLEXITY_DATA;
    },
    
    // 获取颜色稀有度数据
    getColorRarity(limit = 20) {
        return COLOR_RARITY.slice(0, limit);
    },
    
    // 获取3D工厂数据
    getFactory3DData() {
        return FACTORY_3D_DATA;
    },
    
    // 按主题类型过滤
    filterByThemeType(type) {
        return THEME_POPULARITY.filter(t => t.type === type);
    },
    
    // 获取时间跨度内的主题变化
    getThemeEvolution(startYear, endYear) {
        const evolution = {};
        const yearsData = TIMELINE_DATA.filter(d => d.year >= startYear && d.year <= endYear);
        
        yearsData.forEach(yearData => {
            Object.keys(yearData.type_counts).forEach(type => {
                if (!evolution[type]) evolution[type] = [];
                evolution[type].push({
                    year: yearData.year,
                    count: yearData.type_counts[type],
                    share: (yearData.type_counts[type] / yearData.total_sets) * 100
                });
            });
        });
        
        return evolution;
    }
};

